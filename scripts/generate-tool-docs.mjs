/**
 * Generates docs/chat-tools.md and docs/video-tools.md from the tool registry
 * so the docs can never drift from the code.
 *
 *   npm run build && npm run docs:tools    # regenerate
 *   npm run build && npm run docs:check    # fail if stale
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DOCS = join(ROOT, "docs");
const BUILD = join(ROOT, "build", "tools", "registry.js");

if (!existsSync(BUILD)) {
  console.error("build/ is missing — run `npm run build` first.");
  process.exit(1);
}

const { ALL_TOOLS } = await import(new URL("../build/tools/registry.js", import.meta.url));

const PAGES = [
  {
    file: "chat-tools.md",
    title: "Chat, user and moderation tools",
    intro:
      "Tools for messaging, channels, users, tokens and moderation. Toolsets: `chat`, `chat-admin`, `users`, `moderation`.",
    toolsets: ["chat", "chat-admin", "users", "moderation"],
  },
  {
    file: "video-tools.md",
    title: "Video and app tools",
    intro:
      "Tools for calls, participants, recording, broadcasting and app configuration. Toolsets: `video`, `video-admin`, `app`.",
    toolsets: ["video", "video-admin", "app"],
  },
];

/** Peels optional/default/nullable wrappers to reach the concrete type. */
function unwrap(schema) {
  let inner = schema;
  let optional = false;
  for (let depth = 0; depth < 10; depth += 1) {
    const def = inner?.def;
    if (!def?.innerType) break;
    if (def.type === "optional" || def.type === "default") {
      optional = true;
      inner = def.innerType;
      continue;
    }
    // Nullable is not optional: a required nullable field must still be sent.
    if (def.type === "nullable") {
      inner = def.innerType;
      continue;
    }
    break;
  }
  return { inner, optional };
}

function typeName(schema) {
  let json;
  try {
    json = z.toJSONSchema(schema, { io: "input", unrepresentable: "any" });
  } catch {
    return "any";
  }
  if (Array.isArray(json.enum)) return json.enum.map((value) => `\`${value}\``).join(" \\| ");
  if (json.anyOf) return "one of";
  if (typeof json.type === "string") return json.type;
  return "any";
}

function rows(tool) {
  const entries = Object.entries(tool.inputSchema);
  if (entries.length === 0) return ["| _(none)_ | | | |"];

  return entries.map(([name, schema]) => {
    const { inner, optional } = unwrap(schema);
    const description = (schema.description ?? inner.description ?? "").replace(/\|/g, "\\|");
    return `| \`${name}\` | ${typeName(inner)} | ${optional ? "no" : "**yes**"} | ${description} |`;
  });
}

function badge(tool) {
  const flags = [];
  if (tool.annotations.readOnlyHint) flags.push("read-only");
  if (tool.annotations.destructiveHint) flags.push("**destructive**");
  if (tool.annotations.idempotentHint) flags.push("idempotent");
  return flags.length > 0 ? ` — ${flags.join(", ")}` : "";
}

function render(page) {
  const lines = [
    "<!-- Generated by `npm run docs:tools`. Do not edit by hand. -->",
    "",
    `# ${page.title}`,
    "",
    page.intro,
    "",
  ];

  for (const toolset of page.toolsets) {
    const tools = ALL_TOOLS.filter((tool) => tool.toolset === toolset);
    if (tools.length === 0) continue;

    lines.push(`## Toolset \`${toolset}\` (${tools.length} tools)`, "");
    for (const tool of tools) {
      lines.push(`### \`${tool.name}\`${badge(tool)}`, "");
      lines.push(tool.description, "");
      if (tool.aliases?.length) {
        lines.push(
          `Deprecated aliases: ${tool.aliases.map((alias) => `\`${alias}\``).join(", ")}`,
          ""
        );
      }
      lines.push("| Parameter | Type | Required | Description |", "| --- | --- | --- | --- |");
      lines.push(...rows(tool));
      lines.push("");
    }
  }

  lines.push(
    "Every tool also accepts `verbose` (boolean) to return the raw Stream response instead of the compacted view.",
    ""
  );
  return lines.join("\n");
}

const check = process.argv.includes("--check");
mkdirSync(DOCS, { recursive: true });

let stale = false;
for (const page of PAGES) {
  const path = join(DOCS, page.file);
  const next = render(page);
  if (check) {
    const current = existsSync(path) ? readFileSync(path, "utf8") : "";
    if (current !== next) {
      console.error(`docs/${page.file} is out of date — run \`npm run docs:tools\`.`);
      stale = true;
    }
  } else {
    writeFileSync(path, next);
    console.log(`Wrote docs/${page.file}`);
  }
}

if (check && stale) process.exit(1);
if (check) console.log("Tool docs are up to date.");
